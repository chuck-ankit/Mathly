/* ---------------- Category metadata & helpers ---------------- */

export const CATEGORIES: Category[] = [
  'Linear', 'Quadratic', 'Cubic', 'Polynomial', 'Trigonometry', 'Exponential',
  'Logarithmic', 'Rational', 'Absolute Value', 'Geometry', 'Calculus', 'Physics',
  'Probability & Statistics', 'Beautiful',
];

export const DIFFICULTIES: Difficulty[] = ['Beginner', 'Intermediate', 'Advanced', 'Expert'];

export function getExample(id: string): ExampleEquation | undefined {
  return EXAMPLES.find((e) => e.id === id);
}

export function examplesForCategory(category: Category): ExampleEquation[] {
  return EXAMPLES.filter((e) => e.category === category);
}

export function searchExamples(query: string, category: Category | 'All', difficulty: Difficulty | 'All'): ExampleEquation[] {
  const q = query.trim().toLowerCase();
  return EXAMPLES.filter((e) => {
    if (category !== 'All' && e.category !== category) return false;
    if (difficulty !== 'All' && e.difficulty !== difficulty) return false;
    if (!q) return true;
    return (
      e.title.toLowerCase().includes(q) ||
      e.equation.toLowerCase().includes(q) ||
      e.concepts.some((c) => c.toLowerCase().includes(q)) ||
      e.shortDescription.toLowerCase().includes(q)
    );
  });
}

export function relatedExamples(id: string): ExampleEquation[] {
  const self = getExample(id);
  if (!self) return [];
  const related = (self.related ?? [])
    .map((rid) => getExample(rid))
    .filter((e): e is ExampleEquation => Boolean(e));
  // Fill with interesting others if needed
  const fillers = EXAMPLES.filter((e) => e.id !== id && !related.includes(e) && e.difficulty !== 'Expert').slice(0, 6 - related.length);
  return [...related, ...fillers].slice(0, 6);
}